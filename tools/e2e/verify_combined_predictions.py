"""Opt-in live staging verification. Requests fresh forecasts and writes staging data."""

import argparse
import datetime
import json
import math
import os
from pathlib import Path
import time
import urllib.error
import urllib.parse
import urllib.request


MODEL = "nvidia/nemotron-3-super-120b-a12b:free"
OUTCOMES = ("home_win", "draw", "away_win")
GOALS = ("btts", "over25", "two_to_three_goals", "btts_and_over25", "expected_goals")


class VerificationError(Exception):
    pass


def require(condition, message):
    if not condition:
        raise VerificationError(message)


def timestamp(value):
    try:
        parsed = datetime.datetime.fromisoformat(value.replace("Z", "+00:00"))
        require(parsed.tzinfo is not None, "Timestamp must include a timezone")
        return parsed
    except (TypeError, ValueError, AttributeError) as error:
        raise VerificationError("Missing or invalid timestamp") from error


def probability(value):
    return isinstance(value, (int, float)) and not isinstance(value, bool) and math.isfinite(value) and 0 <= value <= 1


def validate_job(job, fixture_id):
    require(job.get("state") == "completed", f"Fixture {fixture_id}: refresh did not complete with all requested sources")
    result = job["result"]
    require(result["fixture_id"] == fixture_id, "Wrong result fixture")
    require(bool(result.get("snapshot_id")), "Missing saved version ID")
    require(result.get("narration_refreshed") is True, "Fresh bilingual narration was not confirmed")
    combined = result["prediction"]
    require(combined["fixture_id"] == fixture_id, "Wrong combined fixture")
    require(combined.get("status") == "complete" and combined.get("all_four_sources_available") is True, "Partial source coverage")
    require(timestamp(combined["captured_at_utc"]) < timestamp(combined["kickoff_utc"]), "Prediction was not captured before kickoff")
    require(timestamp(combined["captured_at_utc"]) >= timestamp(job["started_at_utc"]), "Refresh returned a pre-existing prediction")
    markets = combined["markets"]
    for market in OUTCOMES + GOALS[:-1]:
        require(probability(markets.get(market)), f"Invalid {market} probability")
    require(abs(sum(markets[market] for market in OUTCOMES) - 1) < 1e-8, "1X2 probabilities do not sum to one")
    joint = markets["btts_and_over25"]
    require(max(0, markets["btts"] + markets["over25"] - 1) - 1e-8 <= joint <= min(markets["btts"], markets["over25"]) + 1e-8, "Inconsistent joint goal probability")
    require(isinstance(markets.get("expected_goals"), (int, float)) and math.isfinite(markets["expected_goals"])
            and 0 <= markets["expected_goals"] <= 15, "Invalid expected goals")
    sources = combined["sources"]
    require(len(sources) == 4 and {source["name"] for source in sources} == {"historical", "ml", "provider", "ai"}, "Expected exactly four sources")
    for source in sources:
        require(source.get("markets") is not None, "Missing source markets")
        require(timestamp(source["captured_at_utc"]) <= timestamp(combined["captured_at_utc"]), "Future source evidence")
    for group, weight in ((OUTCOMES, "outcome_weight"), (GOALS, "goals_weight")):
        require(all(probability(source.get(weight)) and source[weight] > 0 for source in sources), "Inactive source weight")
        require(abs(sum(source[weight] for source in sources) - 1) < 1e-8, "Source weights do not sum to one")
        for market in group:
            expected = sum(source["markets"][market] * source[weight]
                           / (sum(source["markets"][outcome] for outcome in OUTCOMES) if group == OUTCOMES else 1)
                           for source in sources)
            require(math.isfinite(expected) and abs(markets[market] - expected) < 1e-8, f"Incorrect weighted {market}")
    ai = next(source for source in sources if source["name"] == "ai")
    require(ai.get("model_version") == MODEL, "Numerical forecast was not generated by the requested NVIDIA free model")
    require(bool(ai.get("rationale", "").strip()), "Missing AI prediction rationale")
    return combined


def validate_analysis(payload, combined):
    require(payload.get("success") is True, "Analysis endpoint returned an unsuccessful envelope")
    match = payload["data"]["match"]
    require(match["id"] == combined["fixture_id"], "Wrong analysis fixture")
    saved = match["combined_prediction"]
    require(saved["captured_at_utc"] == combined["captured_at_utc"], "GET returned an older combined version")
    require(saved["markets"] == combined["markets"], "Stored combined markets changed on read")
    for market in OUTCOMES + GOALS[:3]:
        require(abs(match["prediction"][market]["probability"] - combined["markets"][market]) <= .0001, f"Published {market} differs from saved blend")
    winner = match["match_prediction"]["prediction"]
    require(winner in ("home", "draw", "away"), "Missing whole-match 1X2 prediction")
    winner_market = {"home": "home_win", "draw": "draw", "away": "away_win"}[winner]
    require(combined["markets"][winner_market] >= max(combined["markets"][market] for market in OUTCOMES) - 1e-8, "Whole-match prediction does not select the most likely outcome")
    require(winner == match["prediction"]["match_winner"]["prediction"], "Legacy and new match-winner fields disagree")
    narrative = match.get("ai") or {}
    require(bool(narrative.get("analysis", "").strip()), "Missing persisted narration")
    require(timestamp(narrative.get("generated_at_utc")) >= timestamp(combined["captured_at_utc"]), "Narration predates the combined prediction")
    require(narrative.get("model_version") == MODEL, "Narration was not generated by the requested NVIDIA free model")
    return {"match_prediction": winner, "markets": saved["markets"], "ai": narrative}


class NoRedirects(urllib.request.HTTPRedirectHandler):
    def redirect_request(self, request, response, code, message, headers, new_url):
        raise VerificationError("Refusing redirect while using an admin credential")


class StagingClient:
    def __init__(self, base_url, confirmed_host, key):
        parsed = urllib.parse.urlsplit(base_url)
        require(parsed.scheme == "https" and parsed.hostname and not parsed.username and not parsed.password
                and parsed.path in ("", "/") and not parsed.query and not parsed.fragment, "Use a staging HTTPS origin, without credentials or path")
        require(parsed.netloc == confirmed_host, "Explicit staging host confirmation does not match")
        require(len(key) >= 16, "Set STAGING_ADMIN_API_KEY locally; never pass it as an argument")
        self.origin = base_url.rstrip("/")
        self.key = key
        self.opener = urllib.request.build_opener(NoRedirects())

    def request(self, path, method="GET", authenticated=True):
        require(path.startswith("/api/") and not urllib.parse.urlsplit(path).netloc, "Refusing non-local API/poll URL")
        request = urllib.request.Request(self.origin + path, data=b"" if method == "POST" else None, method=method)
        if authenticated:
            request.add_header("X-API-Key", self.key)
        try:
            with self.opener.open(request, timeout=45) as response:
                return response.status, json.load(response)
        except urllib.error.HTTPError as error:
            return error.code, {}
        except (urllib.error.URLError, TimeoutError, json.JSONDecodeError) as error:
            raise VerificationError(f"Staging request failed ({type(error).__name__}); no automatic write retry") from error


def run(client, fixture_ids, timeout_seconds, reports):
    status, _ = client.request("/api/automation/predictions/0/refresh", "POST", authenticated=False)
    require(status == 401, "Unauthenticated refresh was not rejected; stopping immediately")
    for fixture_id in fixture_ids:
        item = {"fixture_id": fixture_id, "passed": False}
        reports.append(item)
        try:
            status, accepted = client.request(f"/api/automation/predictions/{fixture_id}/refresh?refresh_narration=true", "POST")
            require(status == 202, f"Fixture {fixture_id}: refresh returned HTTP {status}, expected 202")
            require(accepted.get("success") is True, "Refresh returned an unsuccessful envelope")
            item["poll"] = accepted["data"]["poll"]
            deadline = time.monotonic() + timeout_seconds
            job = {}
            while time.monotonic() < deadline:
                status, envelope = client.request(item["poll"])
                require(status == 200, f"Polling returned HTTP {status}; a restart may have lost in-memory job status")
                require(envelope.get("success") is True, "Polling returned an unsuccessful envelope")
                job = envelope["data"]
                item["job"] = job
                if job.get("state") != "running":
                    break
                time.sleep(3)
            require(job.get("state") not in (None, "running"), "Polling timed out; the server job may still be running. Do not blindly resubmit")
            combined = validate_job(job, fixture_id)
            item["languages"] = {}
            for language in ("en", "de"):
                status, payload = client.request(f"/api/analyze/{fixture_id}?language={language}")
                require(status == 200, f"{language} analysis returned HTTP {status}")
                item["languages"][language] = validate_analysis(payload, combined)
            require(item["languages"]["en"]["ai"]["analysis"] != item["languages"]["de"]["ai"]["analysis"], "EN and DE narration are identical")
            item["passed"] = True
        except (VerificationError, KeyError, TypeError, ZeroDivisionError) as error:
            item["error"] = str(error) if isinstance(error, VerificationError) else f"Invalid response contract ({type(error).__name__})"
            break
        time.sleep(4)
    return reports


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--base-url", required=True)
    parser.add_argument("--confirm-staging-host", required=True)
    parser.add_argument("--fixture-id", type=int, action="append", required=True)
    parser.add_argument("--timeout-seconds", type=int, default=1200)
    parser.add_argument("--report", type=Path, required=True)
    args = parser.parse_args()
    report = {"environment": "user-confirmed remote staging",
              "generated_at_utc": datetime.datetime.now(datetime.timezone.utc).isoformat(),
              "live_provider_calls": True, "accuracy_gain_evaluated": False, "fixtures": [], "passed": False}
    try:
        require(3 <= len(set(args.fixture_id)) == len(args.fixture_id) <= 5 and min(args.fixture_id) > 0, "Select 3–5 distinct upcoming internal fixture IDs")
        require(args.timeout_seconds > 0, "Polling timeout must be positive")
        client = StagingClient(args.base_url, args.confirm_staging_host, os.environ.get("STAGING_ADMIN_API_KEY", ""))
        report["base_url"] = client.origin
        run(client, args.fixture_id, args.timeout_seconds, report["fixtures"])
        report["passed"] = len(report["fixtures"]) == len(args.fixture_id) and all(item["passed"] for item in report["fixtures"])
    except (VerificationError, KeyError, TypeError) as error:
        report["error"] = str(error) if isinstance(error, VerificationError) else f"Invalid response contract ({type(error).__name__})"
    args.report.parent.mkdir(parents=True, exist_ok=True)
    args.report.write_text(json.dumps(report, indent=2, ensure_ascii=False) + "\n")
    print(f"{'PASS' if report['passed'] else 'FAIL'}: {args.report}")
    return 0 if report["passed"] else 1


if __name__ == "__main__":
    raise SystemExit(main())
